function thDateFull(d) {
  const x = (d instanceof Date) ? d : new Date(d);
  if (isNaN(x)) return '....................';
  return `${x.getDate()} ${_TH_MONTH[x.getMonth()]} ${x.getFullYear() + 543}`;
}

const DAY_TH = { mon: 'จันทร์', tue: 'อังคาร', wed: 'พุธ', thu: 'พฤหัสบดี', fri: 'ศุกร์', sat: 'เสาร์', sun: 'อาทิตย์' };
const DAY_ORDER = ['mon', 'tue', 'wed', 'thu', 'fri', 'sat', 'sun'];

function workDaysText(days) {
  const a = (Array.isArray(days) ? days : []).filter(d => DAY_TH[d]);
  if (!a.length) return 'ตามที่นายจ้างกำหนด';
  const sorted = DAY_ORDER.filter(d => a.includes(d));
  // ตรวจว่าเป็นช่วงต่อเนื่องหรือไม่ → "จันทร์ถึงศุกร์"
  const idx = sorted.map(d => DAY_ORDER.indexOf(d));
  const contiguous = idx.every((v, i) => i === 0 || v === idx[i - 1] + 1);
  if (contiguous && sorted.length >= 3) return `วัน${DAY_TH[sorted[0]]}ถึงวัน${DAY_TH[sorted[sorted.length - 1]]}`;
  return 'วัน' + sorted.map(d => DAY_TH[d]).join(' วัน');
}

function restDaysText(days) {
  const a = (Array.isArray(days) ? days : []).filter(d => DAY_TH[d]);
  const rest = DAY_ORDER.filter(d => !a.includes(d));
  if (!rest.length) return 'ตามที่นายจ้างกำหนดโดยมีไม่น้อยกว่าสัปดาห์ละหนึ่งวัน';
  return 'วัน' + rest.map(d => DAY_TH[d]).join(' และวัน');
}

