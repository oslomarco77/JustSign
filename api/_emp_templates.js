/* ══════════════════════════════════════════════════════════════
   buildEmpClauses(ctx) → { c1..c18, c19? }
   ══════════════════════════════════════════════════════════════ */
function buildEmpClauses(ctx) {
  const c = ctx || {};
  const out = {};

  // ── ข้อ 1 ──
  const termEnd = c.end_th
    ? ` และมีกำหนดสิ้นสุดในวันที่ ${c.end_th}`
    : ' โดยไม่มีกำหนดระยะเวลาสิ้นสุด';
  out.c1 = EMP_T.c1
    .replace('{POSITION}', c.position || '________________')
    .replace('{EMPLOYMENT_TYPE}', EMPLOYMENT_TYPE_TH[c.employment_type] || 'เต็มเวลา')
    .replace('{START}', c.start_th || '....................')
    .replace('{TERM_END}', termEnd);

  // ── ข้อ 2 ── (เลขข้อย่อยเลื่อนตามว่ามี allowance/bonus หรือไม่)
  let sub = 1;
  let allowLine = '';
  if (Number(c.allowance) > 0) {
    sub++;
    allowLine = `2.${sub} นอกจากค่าจ้างตามข้อ 2.1 นายจ้างตกลงจ่ายค่าตำแหน่งหรือเงินช่วยเหลือค่าครองชีพให้แก่ลูกจ้างในอัตราเดือนละ ${fmtMoney(c.allowance)} บาท (${bahtText(c.allowance)}) ทั้งนี้ เงินดังกล่าวเป็นเงินที่จ่ายเพื่อตอบแทนการทำงานในเวลาทำงานปกติและให้ถือเป็นค่าจ้างตามกฎหมาย\n`;
  }
  let bonusLine = '';
  if ((c.bonus || '').trim()) {
    sub++;
    bonusLine = `2.${sub} โบนัสหรือเงินรางวัลประจำปี: ${String(c.bonus).trim()} ทั้งนี้ การจ่ายโบนัสเป็นดุลพินิจของนายจ้างตามผลประกอบการและผลการปฏิบัติงาน และไม่ถือเป็นค่าจ้าง เว้นแต่นายจ้างจะกำหนดไว้เป็นอย่างอื่น\n`;
  }
  const payN = sub + 1;
  const rcptN = sub + 2;
  out.c2 = EMP_T.c2
    .replace('{SALARY}', fmtMoney(c.salary))
    .replace('{SALARY_TEXT}', bahtText(c.salary))
    .replace('{ALLOWANCE_LINE}', allowLine)
    .replace('{BONUS_LINE}', bonusLine)
    .replace('{PAY_N}', String(payN))
    .replace('{PAYDAY_TEXT}', c.payday_text || 'ภายในวันที่ 5 ของทุกเดือน')
    .replace('{RCPT_N}', String(rcptN));

  // ── ข้อ 3 ──
  const pd = parseInt(c.probation_days, 10) || 0;
  out.c3 = pd > 0 ? EMP_T.c3.replace('{PROBATION_DAYS}', String(pd)) : EMP_T.c3_none;

  // ── ข้อ 4 ──
  const siteLine = (c.client_site || '').trim()
    ? EMP_T.clientSite.replace('{CLIENT_SITE}', String(c.client_site).trim())
    : '';
  out.c4 = EMP_T.c4
    .replace('{WORK_DAYS}', workDaysText(c.work_days))
    .replace('{WORK_START}', c.work_start || '09.00')
    .replace('{WORK_END}', c.work_end || '18.00')
    .replace('{WORK_HOURS}', String(c.work_hours || 8))
    .replace('{LOCATION}', c.location || 'สถานประกอบการของนายจ้าง')
    .replace('{CLIENT_SITE_LINE}', siteLine);

  out.c5 = EMP_T.c5;
  out.c6 = EMP_T.c6.replace('{REST_DAYS}', restDaysText(c.work_days));
  out.c7 = EMP_T.c7;
  out.c8 = EMP_T.c8;

  // ── ข้อ 9 (+ ข้อเสริมแรงงานเด็ก) ──
  out.c9 = EMP_T.c9 + (c.is_minor ? EMP_T.minor : '');

  out.c10 = EMP_T.c10;
  out.c11 = EMP_T.c11;
  out.c12 = EMP_T.c12;
  out.c13 = EMP_T.c13;
  out.c14 = EMP_T.c14;
  out.c15 = EMP_T.c15;
  out.c16 = EMP_T.c16;
  out.c17 = EMP_T.c17;
  out.c18 = EMP_T.c18;

  // ── ข้อ 19 (optional) ──
  const months = clampMonths(c.restrict_months);
  if (c.restrict_level === 'nonsolicit') {
    out.c19 = EMP_T.c19_nonsolicit.replace('{RESTRICT_MONTHS}', String(months));
  } else if (c.restrict_level === 'noncompete') {
    out.c19 = EMP_T.c19_noncompete
      .replace('{RESTRICT_MONTHS}', String(months))
      .replace('{RESTRICT_AREA}', (c.restrict_area || '').trim() || 'ที่นายจ้างประกอบกิจการอยู่ในขณะที่สัญญาสิ้นสุดลง');
  }

  return out;
}

/* จำนวนข้อทั้งหมดของชุด clause ที่สร้าง (18 หรือ 19) */
function empClauseCount(clauses) {
  return clauses && clauses.c19 ? 19 : 18;
}

/* ── helpers ── */
function fmtMoney(n) {
  const v = Number(n) || 0;
  return v.toLocaleString('en-US', { minimumFractionDigits: 0, maximumFractionDigits: 2 });
}

// เพดานความสมเหตุสมผลของข้อจำกัดหลังพ้นสภาพ — ห้ามเกิน 24 เดือน
function clampMonths(m) {
  const v = parseInt(m, 10);
  if (!v || v < 1) return 12;
  return Math.min(v, 24);
}

/* คำนวณค่าจ้างต่อชั่วโมง/ต่อวัน — ใช้แสดง no-work-no-pay และเทียบค่าจ้างขั้นต่ำ */
function wageRates(salary, workDaysPerWeek, hoursPerDay) {
  const s = Number(salary) || 0;
  const dpw = Number(workDaysPerWeek) || 5;
  const hpd = Number(hoursPerDay) || 8;
  const daysPerMonth = (dpw * 52) / 12;              // ≈21.67 สำหรับ จ–ศ
  const perDay = daysPerMonth > 0 ? s / daysPerMonth : 0;
  const perHour = hpd > 0 ? perDay / hpd : 0;
  return {
    days_per_month: Math.round(daysPerMonth * 100) / 100,
    per_day: Math.round(perDay * 100) / 100,
    per_hour: Math.round(perHour * 100) / 100,
  };
}

