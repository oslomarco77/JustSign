/* ── บาทตัวอักษร ───────────────────────────────────────────── */
const _TH_D = ['ศูนย์', 'หนึ่ง', 'สอง', 'สาม', 'สี่', 'ห้า', 'หก', 'เจ็ด', 'แปด', 'เก้า'];
const _TH_P = ['', 'สิบ', 'ร้อย', 'พัน', 'หมื่น', 'แสน'];

// hasHigher = มีหลักที่สูงกว่าซึ่งไม่เป็นศูนย์อยู่ข้างหน้า (เช่น "ล้าน") → เลข 1 หลักหน่วยต้องอ่านว่า "เอ็ด"
function _thNum(nStr, hasHigher) {
  // แปลงจำนวนเต็ม (string ตัวเลขล้วน) เป็นคำอ่านไทย รองรับหลักล้านซ้อน
  nStr = String(nStr).replace(/^0+/, '');
  if (!nStr) return 'ศูนย์';
  if (nStr.length > 6) {
    const head = nStr.slice(0, nStr.length - 6);
    const tail = nStr.slice(-6);
    const tailTxt = /^0{6}$/.test(tail) ? '' : _thNum(tail, true);
    return _thNum(head, hasHigher) + 'ล้าน' + tailTxt;
  }
  let out = '';
  const len = nStr.length;
  for (let i = 0; i < len; i++) {
    const d = parseInt(nStr[i], 10);
    const pos = len - i - 1;             // 0 = หน่วย
    if (d === 0) continue;
    if (pos === 0) {
      if (d === 1 && (len > 1 || hasHigher)) out += 'เอ็ด';
      else out += _TH_D[d];
    } else if (pos === 1) {
      if (d === 1) out += 'สิบ';
      else if (d === 2) out += 'ยี่สิบ';
      else out += _TH_D[d] + 'สิบ';
    } else {
      out += _TH_D[d] + _TH_P[pos];
    }
  }
  return out;
}

function bahtText(amount) {
  const n = Math.round((Number(amount) || 0) * 100) / 100;
  const neg = n < 0;
  const abs = Math.abs(n);
  const baht = Math.floor(abs);
  const satang = Math.round((abs - baht) * 100);
  let out = _thNum(String(baht)) + 'บาท';
  out += satang > 0 ? (_thNum(String(satang)) + 'สตางค์') : 'ถ้วน';
  return (neg ? 'ลบ' : '') + out;
}

